/** Normalise US numbers to (929) 409-9330; leave anything else as typed. */
function xo_format_phone($p) {
    $d = preg_replace('/\D/', '', $p);
    if (strlen($d) === 11 && $d[0] === '1') $d = substr($d, 1);
    return strlen($d) === 10 ? sprintf('(%s) %s-%s', substr($d, 0, 3), substr($d, 3, 3), substr($d, 6)) : $p;
}

